-- Sequill: prints the schema of the "public" schema as SQL, in one cell.
-- Run it in your SQL editor (Supabase, pgAdmin, DBeaver, psql…), copy the result and paste
-- it into Sequill. It reads the catalog only and changes nothing.
-- For another schema, change 'public' on the next line.
WITH ns AS (SELECT oid FROM pg_namespace WHERE nspname = 'public'),
-- Objects an extension (pgcrypto, uuid-ossp…) brought in come back with the extension.
ext AS (SELECT objid FROM pg_depend WHERE deptype = 'e'),
ddl AS (
  -- Enums
  SELECT 1 AS ord, t.typname::text AS name,
    format('CREATE TYPE %s AS ENUM (%s);', t.oid::regtype,
      (SELECT string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder)
       FROM pg_enum e WHERE e.enumtypid = t.oid)) AS sql
  FROM pg_type t JOIN ns ON t.typnamespace = ns.oid
  WHERE t.typtype = 'e' AND t.oid NOT IN (SELECT objid FROM ext)
  UNION ALL
  -- Composite types
  SELECT 1, t.typname::text,
    format('CREATE TYPE %s AS (%s);', t.oid::regtype,
      (SELECT string_agg(format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod)), ', '
         ORDER BY a.attnum)
       FROM pg_attribute a WHERE a.attrelid = t.typrelid AND a.attnum > 0 AND NOT a.attisdropped))
  FROM pg_type t JOIN ns ON t.typnamespace = ns.oid JOIN pg_class c ON c.oid = t.typrelid
  WHERE t.typtype = 'c' AND c.relkind = 'c' AND t.oid NOT IN (SELECT objid FROM ext)
  UNION ALL
  -- Domains
  SELECT 2, t.typname::text,
    format('CREATE DOMAIN %s AS %s%s%s;', t.oid::regtype, format_type(t.typbasetype, t.typtypmod),
      CASE WHEN t.typnotnull THEN ' NOT NULL' ELSE '' END,
      coalesce((SELECT string_agg(' ' || pg_get_constraintdef(k.oid), '')
                FROM pg_constraint k WHERE k.contypid = t.oid), ''))
  FROM pg_type t JOIN ns ON t.typnamespace = ns.oid
  WHERE t.typtype = 'd' AND t.oid NOT IN (SELECT objid FROM ext)
  UNION ALL
  -- Sequences (an identity column's own sequence comes with its column)
  SELECT 3, c.relname::text,
    format('CREATE SEQUENCE %s AS %s INCREMENT BY %s MINVALUE %s MAXVALUE %s START WITH %s%s;',
      c.oid::regclass, format_type(s.seqtypid, NULL), s.seqincrement, s.seqmin, s.seqmax,
      s.seqstart, CASE WHEN s.seqcycle THEN ' CYCLE' ELSE '' END)
  FROM pg_class c JOIN ns ON c.relnamespace = ns.oid JOIN pg_sequence s ON s.seqrelid = c.oid
  WHERE c.relkind = 'S' AND c.oid NOT IN (SELECT objid FROM ext)
    AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'i')
  UNION ALL
  -- Tables: columns, then primary key, unique and check constraints
  SELECT 4, c.relname::text,
    format(E'CREATE TABLE %s (\n  %s\n);', c.oid::regclass, concat_ws(E',\n  ',
      (SELECT string_agg(format('%I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
          CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                             WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END,
          CASE WHEN a.attgenerated = 's'
                 THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
               WHEN ad.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid)
               ELSE '' END,
          CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END), E',\n  ' ORDER BY a.attnum)
       FROM pg_attribute a
       LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
       WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped),
      (SELECT string_agg(format('CONSTRAINT %I %s', k.conname, pg_get_constraintdef(k.oid)),
         E',\n  ' ORDER BY k.contype DESC, k.conname)
       FROM pg_constraint k WHERE k.conrelid = c.oid AND k.contype IN ('p', 'u', 'c'))))
  FROM pg_class c JOIN ns ON c.relnamespace = ns.oid
  WHERE c.relkind IN ('r', 'p') AND NOT c.relispartition AND c.oid NOT IN (SELECT objid FROM ext)
  UNION ALL
  -- Foreign keys, once every table exists
  SELECT 5, k.conname::text,
    format('ALTER TABLE %s ADD CONSTRAINT %I %s;', k.conrelid::regclass, k.conname,
      pg_get_constraintdef(k.oid))
  FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid JOIN ns ON c.relnamespace = ns.oid
  WHERE k.contype = 'f' AND NOT c.relispartition AND c.oid NOT IN (SELECT objid FROM ext)
  UNION ALL
  -- Indexes no constraint made
  SELECT 6, i.relname::text, pg_get_indexdef(i.oid) || ';'
  FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid JOIN pg_class c ON c.oid = x.indrelid
  JOIN ns ON c.relnamespace = ns.oid
  WHERE NOT c.relispartition AND c.oid NOT IN (SELECT objid FROM ext)
    AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.oid AND k.conrelid = c.oid)
  UNION ALL
  -- Functions and procedures
  SELECT 7, p.proname::text, pg_get_functiondef(p.oid) || ';'
  FROM pg_proc p JOIN ns ON p.pronamespace = ns.oid
  WHERE p.prokind IN ('f', 'p') AND p.oid NOT IN (SELECT objid FROM ext)
  UNION ALL
  -- Views and materialized views
  SELECT 8, c.relname::text,
    format(E'CREATE %sVIEW %s AS\n%s', CASE WHEN c.relkind = 'm' THEN 'MATERIALIZED ' ELSE '' END,
      c.oid::regclass, rtrim(pg_get_viewdef(c.oid, true), E'; \n') || ';')
  FROM pg_class c JOIN ns ON c.relnamespace = ns.oid
  WHERE c.relkind IN ('v', 'm') AND c.oid NOT IN (SELECT objid FROM ext)
  UNION ALL
  -- Triggers
  SELECT 9, t.tgname::text, pg_get_triggerdef(t.oid, true) || ';'
  FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN ns ON c.relnamespace = ns.oid
  WHERE NOT t.tgisinternal AND c.oid NOT IN (SELECT objid FROM ext)
)
-- The first line names the database, so Sequill can suggest its name.
SELECT format(E'-- Database: %s\n\n', current_database())
  || string_agg(sql, E'\n\n' ORDER BY ord, name) AS schema
FROM ddl;
